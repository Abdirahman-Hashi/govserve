#!/usr/bin/env node
// Writes infra/.local/stack.env for `make up`: throwaway secrets and local settings. Development
// only; real environments take every value from their secret store (docs/RUNBOOK.md).
import { execFileSync } from 'node:child_process';
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../.local/stack.env');
if (existsSync(out) && !process.argv.includes('--force')) {
  console.log(
    `${out} exists (use --force to regenerate; it resets the local stack's credentials).`,
  );
  process.exit(0);
}
const hex = (n) => randomBytes(n).toString('hex');
const b64 = (n) => randomBytes(n).toString('base64');
const signing = generateKeyPairSync('ed25519').privateKey.export({ format: 'der', type: 'pkcs8' });
// The backup image carries age; its keygen prints the identity plus "# public key: age1…".
const identity = execFileSync(
  'docker',
  ['run', '--rm', '--entrypoint', 'age-keygen', 'govserve/govserve-backup:local'],
  {
    encoding: 'utf8',
  },
);
const recipient = /public key: (age1\w+)/.exec(identity)[1];
const pg = hex(16),
  appDb = hex(16),
  redis = hex(16),
  s3Key = `local${hex(6)}`,
  s3Secret = hex(20);

const values = {
  REGISTRY: 'govserve',
  RELEASE: 'local',
  DEPLOY_ENV: 'staging',
  SITE_ADDRESS: 'http://govserve.localhost',
  WEB_ORIGIN: 'http://govserve.localhost',
  HTTP_PORT: '80',
  HTTPS_PORT: '8443',
  OBJECT_STORE_ORIGIN: 'http://localhost:9100',
  S3_ENDPOINT: 'http://objectstore:9000',
  S3_PUBLIC_ENDPOINT: 'http://localhost:9100',
  S3_BUCKET: 'govserve-documents',
  // RustFS serves buckets by path (http://host/bucket), not by sub-domain.
  S3_FORCE_PATH_STYLE: 'true',
  BACKUP_S3_FORCE_PATH_STYLE: 'true',
  S3_ACCESS_KEY_ID: s3Key,
  S3_SECRET_ACCESS_KEY: s3Secret,
  SMTP_HOST: 'mailpit',
  SMTP_PORT: '1025',
  SMTP_FROM: 'GovServe <no-reply@govserve.localhost>',
  SMTP_PASSWORD: '',
  ALERT_EMAIL_TO: 'ops@govserve.localhost',
  POSTGRES_PASSWORD: pg,
  DATABASE_URL: `postgresql://govserve:${pg}@postgres:5432/govserve`,
  DATABASE_APP_URL: `postgresql://govserve_app:${appDb}@postgres:5432/govserve`,
  REDIS_PASSWORD: redis,
  REDIS_URL: `redis://default:${redis}@redis:6379`,
  CARD_WEBHOOK_SECRET: hex(32),
  JWT_ACCESS_SECRET: hex(32),
  PII_KEYS: `k1:${b64(32)}`,
  BLIND_INDEX_KEY: b64(32),
  SIGNING_KEYS: `local1:${signing.toString('base64')}`,
  METRICS_TOKEN: hex(32),
  BACKUP_S3_ENDPOINT: 'http://objectstore:9000',
  BACKUP_BUCKET: 'govserve-backups',
  BACKUP_S3_ACCESS_KEY_ID: s3Key,
  BACKUP_S3_SECRET_ACCESS_KEY: s3Secret,
  BACKUP_CRYPT_PASSWORD: hex(24),
  BACKUP_AGE_RECIPIENT: recipient,
  // Only for the restore drill; in real environments the identity never touches the VM.
  BACKUP_AGE_IDENTITY: identity.split('\n').find((l) => l.startsWith('AGE-SECRET-KEY-')),
  E2E_STAFF_PASSWORD: `e2e ${hex(8)} Pass`,
};
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `# Generated by infra/scripts/local-secrets.mjs for the local stack only. Do not reuse.\n${Object.entries(
    values,
  )
    // Single-quoted so the file parses both as a Compose env file and in a shell (`source`).
    .map(([k, v]) => `${k}='${v}'`)
    .join('\n')}\n`,
  { mode: 0o600 },
);
console.log(`Wrote ${out}`);
